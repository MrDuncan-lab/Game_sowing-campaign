# Writes the village drawing into the game as a TypeScript module of plain strings and numbers: the summer
# drawing (spring and autumn recolour it with V_SEASON_CSS) and the winter one, each with its roads and defs.
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import villageg as G

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'src', 'art', 'village', 'chernozem.ts')


def tidy(svg):
    # inline styles of animation delays stay; drop whitespace between tags
    return re.sub(r'>\s+<', '><', svg)


def js(v):
    return json.dumps(v, ensure_ascii=False)


variants = {}
for season in G.SEASONS:
    lays = [{'k': k, 'rate': r, 'svg': tidy(svg)} for k, r, svg in G.layers(season)]
    variants[season] = dict(layers=lays, roads=tidy(G.roads_svg(season)), defs=tidy(G.defs(season)))

src = ['// The Chernozem village above the field. Generated by tools/village (python3 export.py): edit the generator,',
       '// not this file. Two drawings: summer (spring and autumn recolour it, see V_SEASON_CSS) and winter.',
       f'export const V_W = {G.W}, V_VH = {G.VH}, V_BOTTOM = {G.BOTTOM};',
       'export interface VLayer { k: string; rate: number; svg: string }',
       'export interface VDrawing { layers: VLayer[]; roads: string; defs: string }',
       f'export const V_SUMMER: VDrawing = {js(variants["summer"])};',
       f'export const V_WINTER: VDrawing = {js(variants["winter"])};',
       f'export const V_SEASON_CSS = {js(G.season_css())};',
       'export interface VAnchor { l: string; x: number; y: number }',
       f'export const V_ANCHORS: Record<string, VAnchor> = {js(G.ANCHORS)};',
       '// the payment cart\'s way from the council down to the gate: x, y and the length run so far, in threes',
       f'export const V_CART: number[] = {js(G.cart_path())};',
       '']
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8').write('\n'.join(src))
print('wrote', OUT, sum(len(x) for x in src), 'chars;', {s: sum(len(l['svg']) for l in v['layers']) + len(v['roads']) for s, v in variants.items()})
