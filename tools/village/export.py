# Writes the village drawing into the game as a TypeScript module of plain strings and numbers.
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import villageg as G

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'src', 'art', 'village', 'chernozem.ts')


def tidy(svg):
    # inline styles of animation delays stay; drop whitespace between tags
    return re.sub(r'>\s+<', '><', svg)


layers = [{'k': k, 'rate': r, 'svg': tidy(svg)} for k, r, svg in G.layers()]
src = ['// The Chernozem village above the field. Generated by tools/village (python3 export.py) from the same',
       '// drawing code as the concept pages: edit the generator, not this file.',
       f'export const V_W = {G.W}, V_VH = {G.VH}, V_BOTTOM = {G.BOTTOM};',
       f'export const V_ROADS = {json.dumps(tidy(G.ROADS_SVG), ensure_ascii=False)};',
       'export interface VLayer { k: string; rate: number; svg: string }',
       f'export const V_LAYERS: VLayer[] = {json.dumps(layers, ensure_ascii=False)};',
       'export interface VAnchor { l: string; x: number; y: number }',
       f'export const V_ANCHORS: Record<string, VAnchor> = {json.dumps(G.ANCHORS, ensure_ascii=False)};',
       '// the payment cart\'s way from the council down to the gate: x, y and the length run so far, in threes',
       f'export const V_CART: number[] = {json.dumps(G.cart_path())};',
       '']
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8').write('\n'.join(src))
print('wrote', OUT, sum(len(x) for x in src), 'chars')
