"""Frame every painted figure portrait for the round avatar: head and shoulders, centred on the head.

The big portraits (pryakhin, the neighbours, the customers, the visitors) are waist-up figures; drawn whole in a
circle the head is small and the sides — cut shoulders, elbows — show at the rim. The head is found from the
silhouette (the top band of the figure), the circle is set to take in the head with the hat and the shoulders.
Writes src/art/portraitFrames.ts: [x, y, size] of the picture in the 100-unit round frame (see Portrait()).
python3 tools/portraits/frames.py
"""
import glob, os, json
from PIL import Image

OUT = 'src/art/portraitFrames.ts'
HEAD_BAND = 0.22      # the top share of the figure taken as the head (with the hat)
DIAM = 0.60           # circle diameter as a share of the figure height
CENTER = 0.28         # circle centre below the top of the figure, as a share of its height
CIRCLE = 92           # the clip circle in Portrait(): r = 46

frames = {}
for f in sorted(glob.glob('src/assets/portraits/*.webp')):
    k = os.path.basename(f)[:-5]
    im = Image.open(f).convert('RGBA'); W, H = im.size
    if max(W, H) < 600: continue          # the small square busts are framed already
    a = im.getchannel('A').point(lambda v: 255 if v > 128 else 0)
    x0, y0, x1, y1 = a.getbbox(); fh = y1 - y0
    band = a.crop((0, y0, W, y0 + int(HEAD_BAND * fh)))
    px = band.load(); xs = []
    for y in range(band.height):
        row = [x for x in range(W) if px[x, y]]
        if row: xs.append((row[0] + row[-1]) / 2)
    cx = sorted(xs)[len(xs) // 2]           # the median of row middles: the hat brim does not pull it aside
    cy = y0 + CENTER * fh
    D = DIAM * fh
    k_ = CIRCLE / D                          # image px → frame units
    size = k_ * min(W, H)                    # Portrait draws the picture as a size×size square, 'slice'
    x = 50 - cx * k_ - (size - W * k_) / 2
    y = 50 - cy * k_ - (size - H * k_) / 2
    frames[k] = [round(x, 1), round(y, 1), round(size, 1)]

with open(OUT, 'w') as o:
    o.write('// Generated by tools/portraits/frames.py: how each painted figure sits in the round avatar,\n')
    o.write('// [x, y, size] in the 100-unit frame, head and shoulders centred on the head. Re-run after adding a portrait.\n')
    o.write('export const AUTO_FRAMES: Record<string, [number, number, number]> = ')
    o.write('{\n' + ''.join(f"  {k}: [{v[0]}, {v[1]}, {v[2]}],\n" for k, v in frames.items()) + '};\n')
print(len(frames), 'frames →', OUT)
