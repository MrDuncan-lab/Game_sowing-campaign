export function orderDialogue(q:Quest):OrderLine[]{
 const b=BUYERS[q.org],text=b.story[q.step]??b.repeat[q.id%b.repeat.length];
 const lines:OrderLine[]=[{who:b.person,name:b.name,text}];
 if(q.org==='orphanage'&&q.step<childLines.length)lines.push(childLines[q.step]);
 return lines;
}
export function pendingOrderVoices(s:GameState){
 return Object.values(s.orgs).flatMap(st=>{
  const q=st?.offer;if(!q || q.expires!==undefined&&q.expires<=s.absWeek || q.createdWeek!==undefined&&q.createdWeek<s.absWeek-1)return [];
  const b=BUYERS[q.org];return [{key:`order:${q.org}:${q.id}`,who:b.person as PersonId,name:b.name,text:b.arrival,org:q.org}];
 }).sort((a,b)=>a.key.localeCompare(b.key));
}
